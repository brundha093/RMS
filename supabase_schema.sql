-- Run this in Supabase SQL Editor before using the online APK.
-- The mobile app uses the Supabase REST API with the anon key.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text unique not null,
  password text not null,
  display_name text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.flats (
  id bigint generated by default as identity primary key,
  flat_number text unique not null,
  flat_type text not null default '',
  tenant_name text not null default '',
  phone text not null default '',
  electricity_number text not null default '',
  monthly_rent numeric not null default 0,
  maintenance numeric not null default 0,
  parking numeric not null default 0,
  repair numeric not null default 0,
  bike_charge numeric not null default 0,
  electricity_due numeric not null default 0,
  electricity_paid numeric not null default 0,
  electricity_arrears numeric not null default 0,
  joining_date text not null default '',
  vacating_date text not null default '',
  tenant_notes text not null default '',
  advance_amount numeric not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.flats add column if not exists advance_amount numeric not null default 0;

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  flat_id bigint not null references public.flats(id) on delete cascade,
  month text not null,
  rent numeric not null default 0,
  maintenance numeric not null default 0,
  parking numeric not null default 0,
  repair numeric not null default 0,
  bike_charge numeric not null default 0,
  electricity numeric not null default 0,
  paid_on date not null default current_date,
  updated_at timestamptz not null default now(),
  unique(flat_id, month)
);


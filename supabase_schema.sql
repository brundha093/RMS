-- Enable REST access. For production, replace these open policies with
-- Supabase Auth-based policies after adding authentication.
alter table public.users enable row level security;
alter table public.flats enable row level security;
alter table public.payments enable row level security;

drop policy if exists rental_users_anon on public.users;
drop policy if exists rental_flats_anon on public.flats;
drop policy if exists rental_payments_anon on public.payments;
create policy rental_users_anon on public.users for all to anon using (true) with check (true);
create policy rental_flats_anon on public.flats for all to anon using (true) with check (true);
create policy rental_payments_anon on public.payments for all to anon using (true) with check (true);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists flats_updated_at on public.flats;
create trigger flats_updated_at before update on public.flats
for each row execute function public.touch_updated_at();

drop trigger if exists payments_updated_at on public.payments;
create trigger payments_updated_at before update on public.payments
for each row execute function public.touch_updated_at();
